
import pandas as pd
VARIABLES={
"过饱和度":("过高可能引起界面失稳、包裹体捕获和缺陷增加。","低/中/高三档过饱和度。","开裂率、包裹体密度、生长速率"),
"降温速率":("过快会增加温度梯度与热应力。","慢/中/快三档降温。","裂纹出现温度、位置、时间"),
"溶液杂质/纯度":("杂质可进入晶格、形成夹杂或改变生长台阶。","净化前后溶液对照。","杂质信号、包裹体、开裂率"),
"籽晶质量":("原有裂纹、位错和包裹体可传播。","高质量籽晶 vs 含缺陷籽晶。","裂纹起点重合率"),
"籽晶类型/取向":("改变生长面与各向异性应力。","只改变取向/类型。","开裂率、裂纹方向"),
"籽晶固定方式":("刚性夹持可造成局部应力集中。","刚性 vs 低约束固定。","固定点裂纹概率"),
"生长温度稳定性":("温度波动会扰动过饱和度和界面。","优化控温前后对照。","温度波动、条纹、开裂率"),
"出炉/取晶冷却":("温差和蒸发可能导致热应力。","原流程 vs 分阶段缓冷。","冷却曲线、裂纹时刻"),
"晶体尺寸/厚度":("尺寸增大会增强温度/浓度梯度。","不同目标尺寸对照。","尺寸-开裂概率"),
"包裹体/散射点":("局部应变与界面不连续可成为裂纹源。","高/低包裹体密度对照。","共定位率、开裂率"),
}
R={"明显异常":3,"偏高/偏快/强约束":3,"可疑":2,"一般/不确定":2,"较好/稳定":1,"偏低/偏慢/低约束":1,"未知":0}
def diagnose(states):
    rows=[]
    for v,(m,e,k) in VARIABLES.items():
        n=R.get(states.get(v,"未知"),0);risk="高" if n==3 else "中" if n==2 else "低" if n==1 else "待核"
        rows.append({"变量":v,"当前状态":states.get(v,"未知"),"风险":risk,"风险分":n,"可能机理":m,"最小对照实验":e,"关键指标":k})
    return pd.DataFrame(rows).sort_values(["风险分","变量"],ascending=[False,True])
def experiment_matrix(sel,base=""):
    return pd.DataFrame([{"变量":v,"基线组":base or "当前标准流程","实验组":VARIABLES[v][1],"保持不变":"除该变量外其余流程一致","关键指标":VARIABLES[v][2],"建议重复":"每组建议≥3个独立样品/批次","判据":"变量变化后指标同步显著变化"} for v in sel])
